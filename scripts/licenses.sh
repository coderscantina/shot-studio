#!/usr/bin/env bash
# Regenerates the third-party licenses from sources/manifest.json and cargo-about 0.9.3:
#
#   THIRD-PARTY-LICENSES.md            bundled assets and vendored libraries, then every crate
#                                      linked into the app with its license text; shipped in
#                                      the app's Contents/Resources
#   crates/shot-app/assets/crates.txt  one line per license, `<license>: <crate>, <crate>`, for
#                                      the About window
#
# release.sh runs it on every release. Install cargo-about with
# `cargo install cargo-about --version 0.9.3 --locked --features cli`.
# Backticks in the printf formats are Markdown, not command substitution.
# shellcheck disable=SC2016
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"

OUT=THIRD-PARTY-LICENSES.md
CRATES=crates/shot-app/assets/crates.txt

about=$(mktemp)
trap 'rm -f "$about"' EXIT
cargo about generate --locked --format json -o "$about"
metadata=$(cargo metadata --format-version 1 --locked)

# The directory a source's license file lives in: the repo, or the crate that vendors it.
license_root() {
  if [ -z "$1" ]; then
    echo .
  else
    jq -r --arg name "$1" '.packages[] | select(.name == $name) | .manifest_path' <<<"$metadata" |
      head -n1 | xargs dirname
  fi
}

{
  printf '# Third-party licenses\n\n'
  printf 'Shot Studio is MIT licensed, see [LICENSE](LICENSE). It bundles the assets and libraries below.\n'
  printf 'Generated by `scripts/licenses.sh` from `sources/manifest.json` and cargo-about. Do not edit by hand.\n\n'
  printf '## Bundled assets and libraries\n\n'
  # Manifest sources that are crates appear under Rust crates with their own license text.
  jq -c '.sources[] | select(.crate == null)' sources/manifest.json | while read -r source; do
    name=$(jq -r .name <<<"$source")
    printf '### %s\n\n' "$name"
    jq -r '"- License: \(.license)",
           (.attribution // empty | "- Attribution: \(.)"),
           "- Source: \(.repository)",
           "- Use: \(.contributes)"' <<<"$source"
    file=$(jq -r '.license_file // empty' <<<"$source")
    if [ -n "$file" ]; then
      root=$(license_root "$(jq -r '.vendored_in // empty' <<<"$source")")
      [ -f "$root/$file" ] || { echo "licenses: $name names $root/$file, which does not exist" >&2; exit 1; }
      printf '\n```text\n%s\n```\n' "$(cat "$root/$file")"
    fi
    printf '\n'
  done
  printf '## Rust crates\n\n'
  jq -r '.licenses[] |
    "### \(.name)\n\nUsed by: \([.used_by[].crate | "\(.name) \(.version)"] | join(", "))\n\n```text\n\(.text | rtrimstr("\n"))\n```\n"' "$about"
} > "$OUT"

jq -r '[.licenses[] | {id, crates: [.used_by[].crate.name]}]
  | group_by(.id)[]
  | "\(.[0].id): \([.[].crates[]] | unique | join(", "))"' "$about" > "$CRATES"

echo "Wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines) and $CRATES ($(wc -l < "$CRATES" | tr -d ' ') licenses)."
